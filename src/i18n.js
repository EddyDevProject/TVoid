let lang = "en";
try { const saved = localStorage.getItem("tvoid.lang"); if (saved && I18N[saved]) lang = saved; } catch (_) {}

function t(key, vars = {}) {
  let s = (I18N[lang] && I18N[lang][key]) ?? I18N.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

/** Backend errors look like "e:code:arg1:arg2"; anything else is shown as-is. */
function tErr(err) {
  const s = String(err);
  if (!s.startsWith("e:")) return s;
  const [, code, ...args] = s.split(":");
  const rest = args.join(":");
  // the last argument may itself contain ':' (OS messages), so only split when a template needs several
  const tpl = I18N.en[`e.${code}`] || "";
  const n = (tpl.match(/\{\d\}/g) || []).length;
  const parts = n > 1 ? [...args.slice(0, n - 1), args.slice(n - 1).join(":")] : [rest];
  return t(`e.${code}`, Object.fromEntries(parts.map((v, i) => [i, v])));
}

/** Launcher log lines look like "l:code:arg". */
function tLog(line) {
  const [, code, ...args] = line.split(":");
  return t(`l.${code}`, { 0: args.join(":") });
}

function applyStatic() {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.innerHTML = t(el.dataset.i18n)));
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
}

function setLang(l) {
  lang = l;
  try { localStorage.setItem("tvoid.lang", l); } catch (_) {}
  applyStatic();
}
